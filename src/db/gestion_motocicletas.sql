--
-- Ejecutar:
--   psql -h localhost -p 5434 -U tu_usuario -d gestion_motocicletas -f src/db/gestion_motocicletas.sql

CREATE TABLE IF NOT EXISTS motocicletas (
    id_motocicleta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca VARCHAR(60) NOT NULL,
    modelo VARCHAR(80) NOT NULL,
    anio INTEGER NOT NULL,
    cilindraje INTEGER NOT NULL,
    precio NUMERIC(12,2) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0,
    estado VARCHAR(10) NOT NULL DEFAULT 'Disponible',
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_cilindraje CHECK (cilindraje > 0),
    CONSTRAINT chk_precio CHECK (precio >= 0),
    CONSTRAINT chk_stock CHECK (stock >= 0),
    CONSTRAINT chk_estado CHECK (estado IN ('Disponible', 'Agotada', 'Inactiva'))
);

